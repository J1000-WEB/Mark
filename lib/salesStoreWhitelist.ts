export function normalizeWhitelistStoreKey(storeName: string) {
  return String(storeName || "")
    .trim()
    .replace(/^오프라인[_\s-]*/i, "")
    .replace(/점$/g, "")
    .replace(/[\s_\-·.()]/g, "")
    .toLowerCase();
}

